def page_config(stats):
    b = []
    b.append('<p class="breadcrumb"><a href="index.html">首页</a> / <span>配置（SPRO）</span></p>')
    b.append('<h1>配置路线：48 个任务的完整索引</h1>')
    b.append('<p class="kicker">SPRO 路径 · 前后台 · 手顺 · 真实画面 —— 全部与教材一致</p>')
    b.append('<p>这一页是「操作手册式」的索引，按 <b>SPRO 的实际顺序</b>分成 A~J 十组。'
             '每个任务给出：教材原文的菜单/IMG 路径、T-code、手顺要点、以及真实系统画面（原文件名标注在图上，可回 Word 原稿核对）。'
             '路径文本可以<b>点击复制</b>。</p>')
    b.append(toc([(g[0] + ". " + g[1], "grp" + g[0]) for g in CONFIG_GROUPS]
                 + [("K. 配置顺序为什么是这个顺序", "why"), ("L. 自检清单", "check")]))
    b.append(tbl(["组", "主题", "任务号", "任务数"], [
        [g[0], g[1], "、".join("%02d" % n for n in g[3]), str(len(g[3]))] for g in CONFIG_GROUPS
    ]))

    for gid, gtitle, gkind, tasks, gdesc in CONFIG_GROUPS:
        b.append('<h2 id="grp%s">%s. %s</h2>' % (gid, gid, gtitle))
        b.append('<p>%s</p>' % gdesc)
        for n in tasks:
            t = TASK[n]
            is_front = n in FRONT
            tags = [("fb", "前台" if is_front else "后台（配置）")]
            for tc in stc(n):
                tags.append(("tc", tc))
            b.append('<div class="steph" id="task%02d"><span class="no">任务 %02d</span><h3>%s</h3>%s</div>'
                     % (n, n, esc(t["title"]),
                        "".join('<span class="%s">%s</span>' % (k, esc(v)) for k, v in tags)))
            b.append('<p>%s</p>' % NOTE1.get(n, ""))
            if spath(n):
                b.append(pathline("教材菜单 / IMG 路径", spath(n)))
            if t["steps"]:
                caps = [s.get("caption", "") for s in t["steps"]]
                items = [(c, "note" if "解释" in c else "") for c in caps if c]
                if items:
                    b.append('<p class="opcap"><span class="lead">手顺要点</span>（教材原文的逐步说明）</p>')
                    b.append(oplist(items, start=1))
            # 画面：第一步 + 最后一步（如果不同）
            picks = []
            mk = lambda st, k=0: simg(n, st, k)

            def has(st):
                return bool(mk(st))

            p1 = mk(1)
            if p1:
                picks.append((p1, 1))
            last = len(t["steps"])
            if last > 1 and has(last):
                p2 = mk(last)
                if p2 and p2 != p1:
                    picks.append((p2, last))
            fig = []
            for i, (p, st) in enumerate(picks):
                cap = scap(n, st)
                if not cap.strip():
                    # 该步没有文字说明（教材是「说明+截图」型）→ 用本任务里第一条非空说明，
                    # 都为空则用任务标题，绝不编造画面内容
                    caps = [s.get("caption", "").strip() for s in t["steps"]]
                    caps = [c for c in caps if c]
                    cap = caps[0] if caps else t["title"]
                if len(cap) > 90:
                    cap = cap[:88] + "…"
                fig.append((p, cap, "%02d-%d" % (n, i + 1)))
            if len(fig) == 1:
                b.append(shot(fig[0][0], no=fig[0][2], cap=fig[0][1], src=src_ref(n)))
            elif fig:
                b.append(shot_grid(fig))
        b.append('<hr class="sep">')

    b.append('<h2 id="why">K. 配置顺序为什么是这个顺序</h2>')
    b.append(steps_list([
        "<b>组织结构</b>（A~C）：数据和单据都要填组织键，组织不存在，后面什么都建不了。",
        "<b>客户账户组与定价</b>（D~F）：主数据的屏幕格式、价格怎么算、记到哪个科目，都属于「规则」。",
        "<b>合作伙伴确定</b>（G）：单据上的角色从哪里来。",
        "<b>主数据</b>（H）：规则定好后再建客户与物料，因为主数据要填的就是这些规则字段。",
        "<b>单据流程</b>（I）：配置和主数据都就绪，订单才能一路跑到发票。",
        "<b>分析</b>（J）：最后打开统计更新，让报表有数据。",
    ]))
    b.append(note("tip", "实训环境的现实",
                  "真实项目里这些配置里可能已有一部分是标准值（可直接用），不需要全部自建。"
                  "课程建议：<b>先把 A~C 与 E 走一遍</b>（组织、装运、定价），其余理解即可，遇到再查这一页。"))

    b.append('<h2 id="check">L. 自检清单</h2>')
    b.append(box("ok", "配置做完后，用这五条验收",
                 "<ol><li>客户主数据：能在至少一个销售范围建出销售视图（VD01/XD01）。</li>"
                 "<li>物料主数据：能建出销售视图，并看到项目类别组、税分类、账户分配组有值。</li>"
                 "<li>条件记录：<code>VK13</code> 能查到该销售范围 + 物料的 PR00 价格。</li>"
                 "<li>订单：<code>VA01</code> 建单后价格自动带出、确认交货日期有值。</li>"
                 "<li>全链：订单 → <code>VL01N</code> 交货 → 发货过账 → <code>VF01</code> 开票 → <code>VF02</code> 下达，"
                 "并在 <code>VF03</code> 里能看到会计凭证。</li></ol>"))
    b.append(steps_list([
        '回 <a href="practice.html"><b>实训任务</b></a> 按 5 个任务实操。',
        '查不到字段含义时看 <a href="glossary.html"><b>术语表</b></a>。',
    ]))
    return b


